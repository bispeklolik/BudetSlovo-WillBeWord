/** Реплики с условными таймкодами (~0,4 с на слово), чтобы работали поиск и статистика. */
export function demoTurns(): { turns: Turn[]; durationSec: number } {
  let t = 0
  let id = 0
  const turns: Turn[] = LINES.map(([spk, text], i) => {
    const startSec = t
    const words = text.split(' ').map((w) => {
      const s = t
      t += 0.4
      return { id: id++, s: Math.round(s * 100) / 100, e: Math.round((t - 0.05) * 100) / 100, t: w }
    })
    t += 0.8
    return { id: `T${i}`, spk, startSec, words }
  })
  return { turns, durationSec: Math.ceil(t) }
}

