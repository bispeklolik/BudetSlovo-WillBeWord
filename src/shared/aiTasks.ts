/** «Искать внимательно»: одна запись целиком — только то, что относится к вопросу. */
const EXTRACT_SYSTEM =
  'Ты помогаешь специалисту найти в записи разговора всё, что относится к вопросу. Ниже — расшифровка, ' +
  'у каждой реплики время в квадратных скобках [мм:сс]. Выпиши коротко пунктами «- …» всё, что отвечает на ' +
  'вопрос, после каждого пункта — время реплики, точно как в тексте: [12:34]. Не выдумывай. ' +
  'Если в этой записи ничего по вопросу нет — ответь одним словом: НЕТ. Пиши только по-русски.'

/** Вопрос и прошлые вопросы — в system: при чтении частями они нужны каждой части. */
export function extractSystem(question: string, history: AskTurn[]): string {
  const past = history
    .slice(-3)
    .map((h) => `Вопрос: ${h.q}\nОтвет: ${h.a.slice(0, 800)}`)
    .join('\n\n')
  return EXTRACT_SYSTEM + (past ? '\n\nПРЕДЫДУЩИЕ ВОПРОСЫ:\n' + past : '') + '\n\nВОПРОС: ' + question.trim()
}

