  '- «Что стоит на месте»: только то, в чём нет сдвигов до последней сессии. Тему из «Что изменилось» сюда не ставь.\n' +
  '- «Договорённости»: что задавалось и что с этим стало в следующих сессиях.\n' +
  '- «Вопросы к следующей сессии»: 3–5 вопросов, которые стоит прояснить.\n' +
  'Ссылайся на сессии так: (сессия 3). Списки — «- …». Без вступлений.'

export function dynamicsInput(briefs: { title: string; date: string; brief: string }[]): string {
  return briefs.map((b, i) => `### Сессия ${i + 1} — «${b.title}» (${b.date})\n${b.brief.trim()}`).join('\n\n')
}

// ---------- «Что я пропустил?» ----------
export function missedSystem(minutes: number): string {
  return (
    `Ниже — расшифровка последних ${minutes} мин идущего разговора (два голоса: специалист и собеседник, ` +
    'реплики не разделены). Специалист отвлёкся и спрашивает: «что я пропустил?». ' +
    'Ответь 3–6 короткими пунктами «- …»: о чём шла речь, что спросили или попросили, ' +
    'о чём договорились, на что стоит ответить. Без вступлений. Если текста почти нет — так и скажи.'
  )
}

