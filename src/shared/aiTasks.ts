/** Вопрос + прошлые вопросы-ответы (для уточнений «а подробнее?») + контекст. */
export function buildAskInput(question: string, history: AskTurn[], context: string): string {
  const past = history
    .slice(-3)
    .map((h) => `Вопрос: ${h.q}\nОтвет: ${h.a.slice(0, 1500)}`)
    .join('\n\n')
  return (
    'ФРАГМЕНТЫ:\n' +
    context +
    (past ? '\n\nПРЕДЫДУЩИЕ ВОПРОСЫ В ЭТОМ РАЗГОВОРЕ:\n' + past : '') +
    '\n\nВОПРОС: ' +
    question.trim()
  )
}

