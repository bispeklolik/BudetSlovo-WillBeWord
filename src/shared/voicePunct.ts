// Пунктуация голосом (волна 6): «запятая», «с новой строки», «вопросительный
// знак» → знаки. Работает до ИИ-чистки и без неё. «Точку» командой не делаем:
// это обычное слово («точка зрения», «точка сбора»), и правило по большой
// букве после него удаляло слово из текста (ревью волны 6). Точки ставят
// распознавание и чистка. Остальной текст не трогаем: время 14:30, число 2,5,
// ссылки и многоточия остаются как есть — правим только места команд.

interface Rule {
  re: RegExp
  to: string
  /** после знака начинается новое предложение — следующее слово с заглавной */
  cap?: boolean
}

// Метка «здесь сработала команда конца предложения» — убираем до выдачи.
const CAP = '\u0001'

const W = '[\\p{L}\\p{N}]'
// Перед паузой движок сам ставит «.» или «,»: «чувствуете. Вопросительный знак» —
// такую точку знак из команды заменяет (иначе вышло бы «.?»). Только после слова
// от 2 букв: точка сокращения «т.д. запятая» остаётся.
const BEFORE = '(?:(?<=\\p{L}{2})[.,][ \\t]*)?'
const word = (phrase: string, eatBefore = false): RegExp =>
  new RegExp(`${eatBefore ? BEFORE : ''}(?<!${W})${phrase.split(' ').join('[\\s,]+')}(?!${W})[.,]?`, 'giu')

// Длинные фразы — раньше коротких («точка с запятой» раньше «точки» и «запятой»).
const RULES: Rule[] = [
  { re: word('с новой строки'), to: '\n', cap: true },
  { re: word('новая строка'), to: '\n', cap: true },
  { re: word('с нового абзаца'), to: '\n\n', cap: true },
  { re: word('новый абзац'), to: '\n\n', cap: true },
  { re: word('точка с запятой', true), to: ';' },
  { re: word('вопросительный знак', true), to: '?', cap: true },
  { re: word('восклицательный знак', true), to: '!', cap: true },
  { re: word('открыть кавычки'), to: '«' },
  { re: word('закрыть кавычки'), to: '»' },
  { re: word('открыть скобку'), to: '(' },
  { re: word('закрыть скобку'), to: ')' },
  { re: word('многоточие', true), to: '…' },
  { re: word('двоеточие', true), to: ':' },
  { re: word('запятая', true), to: ',' }
]

/** Знаки, которые прилипают к слову слева, и открывающие — к слову справа. */
function tidy(s: string): string {
  return s
    .replace(/[ \t]+([,.;:!?…»)])/g, '$1') // пробел перед знаком
    .replace(/([«(])[ \t]+/g, '$1') // пробел после открывающего
    .replace(/([,;:])(?=[\p{L}«(])/gu, '$1 ') // после запятой перед словом — пробел (14:30 и 2,5 не трогаем)
    .replace(/([,;:!?…])\1+/g, '$1') // «,,» и «??» от движка и от команды сразу
    .replace(/(?:\.\.\.|…){2,}/g, '…') // «...» от движка + «многоточие»
    .replace(/[ \t]*\n[ \t]*/g, '\n')
    .replace(/[ \t]{2,}/g, ' ')
    .replace(/^(\p{Ll})/u, (c: string) => c.toUpperCase())
    .trim()
}

export function applyVoicePunctuation(text: string): string {
  let out = text
  let hit = false
  for (const r of RULES)
    out = out.replace(r.re, () => {
      hit = true
      return r.to + (r.cap ? CAP : '')
    })
  if (!hit) return text // команд нет — текст как был, до последнего пробела
  // После «?», «!» и новой строки — с заглавной (только там, где была команда).
  out = out.replace(new RegExp(`${CAP}([ \\t\\n]*)(\\p{Ll})`, 'gu'), (_, sp: string, c: string) => sp + c.toUpperCase())
  return tidy(out.split(CAP).join(''))
}
